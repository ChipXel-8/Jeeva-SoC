#include "pragya_test.h"
#include <stdint.h>

volatile int a, b, c, d, e, f;
volatile unsigned ua, ub, uc;

int main(void)
{

/*============================================================*
 * 1. DIVU : rs2 = x26
 *============================================================*/

asm volatile(
    "mv x6,  %0\n"
    "mv x26, %1\n"
    "divu x5, x6, x26\n"
    :
    : "r"(1000), "r"(10)
    : "x6", "x26", "x5"
);


/*============================================================*
 * 2. MUL : rs2 = x25
 *============================================================*/

asm volatile(
    "mv x6,  %0\n"
    "mv x25, %1\n"
    "mul x5, x6, x25\n"
    :
    : "r"(12), "r"(7)
    : "x6", "x25", "x5"
);


/*============================================================*
 * 3. MULHU : rs2 = x24
 *============================================================*/

asm volatile(
    "li x6, 0x00010000\n"
    "li x24, 0x00000100\n"
    "mulhu x5, x6, x24\n"
    :
    :
    : "x6", "x24", "x5"
);


/*============================================================*
 * 4. REM : rs2 = x21
 *============================================================*/

asm volatile(
    "mv x6,  %0\n"
    "mv x21, %1\n"
    "rem x5, x6, x21\n"
    :
    : "r"(101), "r"(10)
    : "x6", "x21", "x5"
);


/*============================================================*
 * 5. DIV : rs2 = x13
 *============================================================*/

asm volatile(
    "mv x6,  %0\n"
    "mv x13, %1\n"
    "div x5, x6, x13\n"
    :
    : "r"(1000), "r"(10)
    : "x6", "x13", "x5"
);


/*============================================================*
 * 6. MULHSU : rs2 = x10
 *============================================================*/

asm volatile(
    "li x6, -100000\n"
    "li x10, 200\n"
    "mulhsu x5, x6, x10\n"
    :
    :
    : "x6", "x10", "x5"
);


/*============================================================*
 * 7. DIV : rs2 = x8
 *
 * x8 = s0/fp.
 *
 * Save the original x8 on stack.
 * Put divisor in x8.
 * Execute DIV.
 * Restore original x8.
 *============================================================*/

asm volatile(
    "sw x8, 0(sp)\n"
    "li x6, -1000\n"
    "li x8, 10\n"
    "div x5, x6, x8\n"
    "lw x8, 0(sp)\n"
    :
    :
    : "x6", "x5", "memory"
);


/*============================================================*
 * 8. MUL : rs2 = x3
 *============================================================*/

asm volatile(
    "mv x6, %0\n"
    "mv x3, %1\n"
    "mul x5, x6, x3\n"
    :
    : "r"(-12), "r"(7)
    : "x6", "x3", "x5"
);


/*============================================================*
 * 9. DIVU : rs2 = x2
 *
 * IMPORTANT:
 *
 * x2 = SP.
 *
 * We do NOT modify x2.
 * We simply use the current stack pointer as rs2.
 *
 * This is specifically to hit:
 *
 *     cross_instr_rs2
 *     DIVU + x2
 *
 *============================================================*/

asm volatile(
    "mv x6, %0\n"
    "divu x5, x6, x2\n"
    :
    : "r"(1000)
    : "x6", "x5"
);


/*============================================================*
 * Additional RV32M directed operations
 *============================================================*/

/* MUL special values */

a = 0;
b = 1234;

if (a * b != 0)
    test_fail();


a = 1;
b = 5678;

if (a * b != 5678)
    test_fail();


a = -1;
b = 123;

if (a * b != -123)
    test_fail();


a = -10;
b = -20;

if (a * b != 200)
    test_fail();


a = 32767;
b = 32767;

c = a * b;

if (c != 1073676289)
    test_fail();


/*============================================================*
 * DIV special values
 *============================================================*/

a = 100;
b = 5;

if (a / b != 20)
    test_fail();


a = -100;
b = 5;

if (a / b != -20)
    test_fail();


a = 100;
b = -5;

if (a / b != -20)
    test_fail();


a = -100;
b = -5;

if (a / b != 20)
    test_fail();


/*============================================================*
 * REM special values
 *============================================================*/

a = 101;
b = 10;

if (a % b != 1)
    test_fail();


a = -101;
b = 10;

if (a % b != -1)
    test_fail();


a = 101;
b = -10;

if (a % b != 1)
    test_fail();


a = -101;
b = -10;

if (a % b != -1)
    test_fail();


/*============================================================*
 * Unsigned division
 *============================================================*/

ua = 100;
ub = 3;

uc = ua / ub;

if (uc != 33)
    test_fail();


uc = ua % ub;

if (uc != 1)
    test_fail();


/*============================================================*
 * RAW DEPENDENCY
 *============================================================*/

a = 12;

b = a * 5;
c = b / 3;
d = c % 7;
e = d * 11;
f = e / 2;

if (f != 22)
    test_fail();


/*============================================================*
 * Continuous M operations
 *============================================================*/

a = 2;

for (int i = 1; i <= 20; i++)
{
    a = a * i;
    a = a / i;
}

if (a != 2)
    test_fail();


/*============================================================*
 * Mixed MUL / DIV / REM
 *============================================================*/

a = 55;

b = a * 4;
c = b / 5;
d = c % 8;
e = d * 7;
f = e / 2;

if (f < 0)
    test_fail();


/*============================================================*
 * Stress loop
 *============================================================*/

a = 12345;

for (int i = 1; i < 50; i++)
{
    a = a * 3;
    a = a / 3;
    a = a % 100000;
}

if (a <= 0)
    test_fail();


/*============================================================*
 * PASS
 *============================================================*/

test_pass();

return 0;
}