#include "pragya_test.h"
#include <stdint.h>

volatile int a, b, c, d;

int main(void)
{
    /*------------------------------------------*
     * Basic ALU
     *------------------------------------------*/
    a = 10;
    b = 10;

    /* BEQ taken */
    if (a == b)
        c = 100;
    else
        c = 1;

    if (c != 100)
        test_fail();

    /* BNE not taken */
    if (a != b)
        test_fail();

    /* BNE taken */
    b = 20;

    if (a != b)
        c = 200;
    else
        c = 2;

    if (c != 200)
        test_fail();

    /*------------------------------------------*
     * BLT taken
     *------------------------------------------*/
    a = -10;
    b = 5;

    if (a < b)
        c = 300;
    else
        c = 3;

    if (c != 300)
        test_fail();

    /*------------------------------------------*
     * BGE taken
     *------------------------------------------*/
    a = 20;
    b = 10;

    if (a >= b)
        c = 400;
    else
        c = 4;

    if (c != 400)
        test_fail();

    /*------------------------------------------*
     * BLTU taken
     *------------------------------------------*/
    {
        unsigned ua = 1;
        unsigned ub = 10;

        if (ua < ub)
            c = 500;
        else
            c = 5;
    }

    if (c != 500)
        test_fail();

    /*------------------------------------------*
     * BGEU taken
     *------------------------------------------*/
    {
        unsigned ua = 20;
        unsigned ub = 10;

        if (ua >= ub)
            c = 600;
        else
            c = 6;
    }

    if (c != 600)
        test_fail();

    /*------------------------------------------*
     * Backward branch
     *------------------------------------------*/
    a = 0;

    for (int i = 0; i < 5; i++)
        a = a + 1;

    if (a != 5)
        test_fail();

    /*------------------------------------------*
     * Taken branch with memory operation
     *------------------------------------------*/
    a = 100;
    b = 100;

    if (a == b) {
        c = a + 10;
    }

    if (c != 110)
        test_fail();

    /*------------------------------------------*
     * JAL/JALR generated by function call
     *------------------------------------------*/
    c = 10;

    c = c + 5;

    if (c != 15)
        test_fail();

    test_pass();

    return 0;
}