#include "pragya_test.h"
#include <stdint.h>

volatile uint32_t sink;

int main(void)
{
    uint32_t value;

    /*
     * ============================================================
     * PRAGYA IMMEDIATE GENERATOR - ALL TYPES
     *
     * I-type
     * S-type
     * B-type
     * U-type
     * J-type
     *
     * ============================================================
     */


    /*
     * ------------------------------------------------------------
     * I-TYPE
     * ------------------------------------------------------------
     */

    asm volatile(
        "li x5, 0x100\n"
        "addi x6, x5, 1\n"
        "andi x7, x6, 0x7f\n"
        "ori  x8, x7, 0x55\n"
        "xori x9, x8, 0x2a\n"
        :
        :
        : "memory"
    );


    /*
     * ------------------------------------------------------------
     * S-TYPE
     * ------------------------------------------------------------
     */

    asm volatile(
        "li x5, 0x80008000\n"
        "li x6, 0x12345678\n"

        "sw x6, 0(x5)\n"
        "sw x6, 4(x5)\n"
        "sw x6, 8(x5)\n"
        "sw x6, 12(x5)\n"
        :
        :
        : "memory"
    );


    /*
     * ------------------------------------------------------------
     * B-TYPE
     * ------------------------------------------------------------
     */

    asm volatile(
        "li x5, 1\n"
        "li x6, 1\n"

        "beq x5, x6, b1\n"
        "li x7, 0x11111111\n"

        "b1:\n"
        "bne x5, x6, b2\n"
        "li x7, 0x22222222\n"

        "b2:\n"
        "blt x5, x6, b3\n"
        "li x7, 0x33333333\n"

        "b3:\n"
        "bge x5, x6, b4\n"
        "li x7, 0x44444444\n"

        "b4:\n"
        "bltu x5, x6, b5\n"
        "li x7, 0x55555555\n"

        "b5:\n"
        "bgeu x5, x6, b6\n"

        "b6:\n"
        :
        :
        : "memory"
    );


    /*
     * ------------------------------------------------------------
     * U-TYPE
     * ------------------------------------------------------------
     */

    asm volatile(
        "lui   x10, 0x12345\n"
        "lui   x11, 0xABCDE\n"
        "lui   x12, 0xFFFFF\n"

        "auipc x13, 0x11111\n"
        "auipc x14, 0xAAAAA\n"
        "auipc x15, 0xFFFFF\n"
        :
        :
        : "memory"
    );


    /*
     * ------------------------------------------------------------
     * J-TYPE
     * ------------------------------------------------------------
     */

    asm volatile(
        "jal x1, j1\n"
        "li x16, 0x11111111\n"

        "j1:\n"
        "jal x1, j2\n"
        "li x16, 0x22222222\n"

        "j2:\n"
        "jal x0, j3\n"
        "li x16, 0x33333333\n"

        "j3:\n"
        :
        :
        : "memory"
    );


    /*
     * ------------------------------------------------------------
     * Save result
     * ------------------------------------------------------------
     */

    value = 0xCAFEBABE;
    sink = value;

    test_pass();

    while (1)
        asm volatile("nop");

    return 0;
}