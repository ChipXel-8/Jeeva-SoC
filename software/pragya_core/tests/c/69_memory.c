#include "pragya_test.h"
#include <stdint.h>

volatile uint32_t mem0;
volatile uint32_t mem1;
volatile uint32_t mem2;
volatile uint32_t mem3;

volatile int a, b, c, d, e;

int main(void)
{
    uintptr_t addr;

    /*============================================================*
     * STORE / LOAD
     *============================================================*/

    a = 100;

    addr = (uintptr_t)&mem0;

    asm volatile(
        "mv x10, %0\n"
        "mv x20, %1\n"
        "sw x10, 0(x20)\n"
        :
        : "r"(a), "r"(addr)
        : "x10", "x20", "memory"
    );

    asm volatile(
        "mv x20, %0\n"
        "lw x11, 0(x20)\n"
        :
        : "r"(addr)
        : "x11", "x20", "memory"
    );

    /* LOAD -> USE */
    asm volatile(
        "add x12, x11, x11\n"
        :
        :
        : "x12"
    );

    /*============================================================*
     * SECOND STORE / LOAD
     *============================================================*/

    b = 200;
    addr = (uintptr_t)&mem1;

    asm volatile(
        "mv x13, %0\n"
        "mv x20, %1\n"
        "sw x13, 0(x20)\n"
        :
        : "r"(b), "r"(addr)
        : "x13", "x20", "memory"
    );

    asm volatile(
        "mv x20, %0\n"
        "lw x14, 0(x20)\n"
        :
        : "r"(addr)
        : "x14", "x20", "memory"
    );

    asm volatile(
        "add x15, x14, x14\n"
        :
        :
        : "x15"
    );

    /*============================================================*
     * THIRD STORE / LOAD
     *============================================================*/

    c = 300;
    addr = (uintptr_t)&mem2;

    asm volatile(
        "mv x16, %0\n"
        "mv x20, %1\n"
        "sw x16, 0(x20)\n"
        :
        : "r"(c), "r"(addr)
        : "x16", "x20", "memory"
    );

    asm volatile(
        "mv x20, %0\n"
        "lw x17, 0(x20)\n"
        :
        : "r"(addr)
        : "x17", "x20", "memory"
    );

    asm volatile(
        "sub x18, x17, x17\n"
        :
        :
        : "x18"
    );

    /*============================================================*
     * FORWARD A
     *============================================================*/

    asm volatile(
        "li x5, 10\n"
        "li x6, 20\n"
        "add x5, x5, x6\n"
        "add x7, x5, x0\n"
        :
        :
        : "x5", "x6", "x7"
    );

    /*============================================================*
     * FORWARD B
     *============================================================*/

    asm volatile(
        "li x5, 30\n"
        "li x6, 40\n"
        "add x5, x5, x6\n"
        "add x7, x0, x5\n"
        :
        :
        : "x5", "x6", "x7"
    );

    /*============================================================*
     * FORWARD A + B
     *============================================================*/

    asm volatile(
        "li x5, 10\n"
        "li x6, 20\n"
        "add x5, x5, x0\n"
        "add x6, x6, x0\n"
        "add x7, x5, x6\n"
        :
        :
        : "x5", "x6", "x7"
    );

    /*============================================================*
     * LONG RAW CHAIN
     *============================================================*/

    asm volatile(
        "li x5, 2\n"
        "add x6, x5, x5\n"
        "add x7, x6, x6\n"
        "add x10, x7, x7\n"
        "add x11, x10, x10\n"
        :
        :
        : "x5", "x6", "x7", "x10", "x11"
    );

    /*============================================================*
     * MEMORY + RAW
     *============================================================*/

    d = 55;
    addr = (uintptr_t)&mem3;

    asm volatile(
        "mv x12, %0\n"
        "mv x20, %1\n"
        "sw x12, 0(x20)\n"
        "lw x13, 0(x20)\n"
        "add x14, x13, x13\n"
        "sub x15, x14, x13\n"
        :
        : "r"(d), "r"(addr)
        : "x12", "x13", "x14", "x15", "x20", "memory"
    );

    /*============================================================*
     * BRANCH TAKEN
     *============================================================*/

    asm volatile(
        "li x5, 1\n"
        "li x6, 1\n"
        "beq x5, x6, 1f\n"
        "li x7, 0x111\n"
        "1:\n"
        "li x7, 0x222\n"
        :
        :
        : "x5", "x6", "x7"
    );

    /*============================================================*
     * BRANCH NOT TAKEN
     *============================================================*/

    asm volatile(
        "li x5, 1\n"
        "li x6, 2\n"
        "beq x5, x6, 1f\n"
        "li x7, 123\n"
        "1:\n"
        "li x10, 456\n"
        :
        :
        : "x5", "x6", "x7", "x10"
    );

    /*============================================================*
     * FINAL LOAD
     *============================================================*/

    addr = (uintptr_t)&mem0;

    asm volatile(
        "mv x20, %0\n"
        "lw x11, 0(x20)\n"
        "add x12, x11, x11\n"
        :
        : "r"(addr)
        : "x11", "x12", "x20", "memory"
    );

    test_pass();

    return 0;
}
