#include "pragya_test.h"
#include <stdint.h>

volatile int a,b;
volatile unsigned ua,ub;
volatile int sum;

int main(void)
{
    sum = 0;

    /*------------------------------------------
      BEQ Taken
    ------------------------------------------*/

    a = 10;
    b = 10;

    if(a==b)
        sum++;

    /*------------------------------------------
      BEQ Not Taken
    ------------------------------------------*/

    a = 10;
    b = 20;

    if(a==b)
        test_fail();
    else
        sum++;

    /*------------------------------------------
      BNE Taken
    ------------------------------------------*/

    if(a!=b)
        sum++;

    /*------------------------------------------
      BNE Not Taken
    ------------------------------------------*/

    a = 50;
    b = 50;

    if(a!=b)
        test_fail();
    else
        sum++;

    /*------------------------------------------
      BLT Taken
    ------------------------------------------*/

    a = -10;
    b = 5;

    if(a<b)
        sum++;

    /*------------------------------------------
      BLT Not Taken
    ------------------------------------------*/

    a = 10;
    b = 5;

    if(a<b)
        test_fail();
    else
        sum++;

    /*------------------------------------------
      BGE Taken
    ------------------------------------------*/

    a = 20;
    b = 20;

    if(a>=b)
        sum++;

    a = 25;

    if(a>=b)
        sum++;

    /*------------------------------------------
      BGE Not Taken
    ------------------------------------------*/

    a = 5;
    b = 10;

    if(a>=b)
        test_fail();
    else
        sum++;

    /*------------------------------------------
      BLTU Taken
    ------------------------------------------*/

    ua = 10;
    ub = 20;

    if(ua<ub)
        sum++;

    /*------------------------------------------
      BLTU Not Taken
    ------------------------------------------*/

    ua = 40;
    ub = 20;

    if(ua<ub)
        test_fail();
    else
        sum++;

    /*------------------------------------------
      BGEU Taken
    ------------------------------------------*/

    ua = 30;
    ub = 30;

    if(ua>=ub)
        sum++;

    ua = 40;

    if(ua>=ub)
        sum++;

    /*------------------------------------------
      BGEU Not Taken
    ------------------------------------------*/

    ua = 5;
    ub = 10;

    if(ua>=ub)
        test_fail();
    else
        sum++;

    /*------------------------------------------
      Alternating Branches
    ------------------------------------------*/

    for(int i=0;i<50;i++)
    {
        if(i&1)
            sum++;
        else
            sum--;
    }

    /*------------------------------------------
      Nested Branches
    ------------------------------------------*/

    for(int i=0;i<10;i++)
    {
        for(int j=0;j<10;j++)
        {
            if(i==j)
                sum++;
            else if(i<j)
                sum+=2;
            else
                sum+=3;
        }
    }

    /*------------------------------------------
      Branch Dependency
    ------------------------------------------*/

    a = 1;

    for(int i=0;i<20;i++)
    {
        a = a + i;

        if(a&1)
            sum++;
        else
            sum--;
    }

    /*------------------------------------------
      Final Check
    ------------------------------------------*/

    if(sum==0)
        test_fail();

    test_pass();

    return 0;
}
