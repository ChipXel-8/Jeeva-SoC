#include "pragya_test.h"
#include <stdint.h>

volatile int a,b,c,d;

int main(void)
{
    /*------------------------------------------
      Positive Remainder
    ------------------------------------------*/

    a = 100;
    b = 7;
    c = a % b;

    if(c != 2)
        test_fail();

    /*------------------------------------------
      Negative Dividend
    ------------------------------------------*/

    a = -100;
    b = 7;
    c = a % b;

    if(c != -2)
        test_fail();

    /*------------------------------------------
      Negative Divisor
    ------------------------------------------*/

    a = 100;
    b = -7;
    c = a % b;

    if(c != 2)
        test_fail();

    /*------------------------------------------
      Both Negative
    ------------------------------------------*/

    a = -100;
    b = -7;
    c = a % b;

    if(c != -2)
        test_fail();

    /*------------------------------------------
      Zero Dividend
    ------------------------------------------*/

    a = 0;
    b = 5;
    c = a % b;

    if(c != 0)
        test_fail();

    /*------------------------------------------
      Divide By Zero
      RV32M REM returns dividend
    ------------------------------------------*/

    a = 12345;
    b = 0;
    c = a % b;

    if(c != 12345)
        test_fail();

    /*------------------------------------------
      INT_MIN % -1
      RV32M returns 0
    ------------------------------------------*/

    a = 0x80000000;
    b = -1;
    c = a % b;

    if(c != 0)
        test_fail();

    /*------------------------------------------
      Power of Two
    ------------------------------------------*/

    a = 4099;
    b = 16;

    c = a % b;

    if(c != 3)
        test_fail();

    /*------------------------------------------
      RAW Dependency
    ------------------------------------------*/

    a = 1000;
    b = a % 97;
    c = b + 50;
    d = c % 11;

    if(d != ((1000%97)+50)%11)
        test_fail();

    /*------------------------------------------
      Consecutive REM Operations
    ------------------------------------------*/

    a = 123456;

    for(int i=3;i<15;i++)
        a = a % i;

    if(a < 0)
        test_fail();

    /*------------------------------------------
      Mixed MUL/DIV/REM
    ------------------------------------------*/

    a = 33;
    b = 17;

    c = a * b;
    d = c % 29;

    if(d != ((33*17)%29))
        test_fail();

    test_pass();

    return 0;
}
