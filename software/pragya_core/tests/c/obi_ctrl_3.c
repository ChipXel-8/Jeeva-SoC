#include "pragya_test.h"
#include <stdint.h>

volatile uint32_t sink;

int main(void)
{
    volatile uint8_t  *mem8;
    volatile uint16_t *mem16;
    volatile uint32_t *mem32;

    uint32_t a;
    uint32_t b;

    mem8  = (volatile uint8_t  *)0x80008020;
    mem16 = (volatile uint16_t *)0x80008040;
    mem32 = (volatile uint32_t *)0x80008060;

    /*
     * ============================================================
     * DATA MEMORY WRAPPER TEST
     * ============================================================
     */

    /*
     * ------------------------------------------------------------
     * WORD STORES
     * ------------------------------------------------------------
     */

    mem32[0] = 0x00000000;
    mem32[1] = 0xFFFFFFFF;
    mem32[2] = 0xAAAAAAAA;
    mem32[3] = 0x55555555;
    mem32[4] = 0x12345678;
    mem32[5] = 0x87654321;
    mem32[6] = 0x80000000;
    mem32[7] = 0x7FFFFFFF;

    /*
     * ------------------------------------------------------------
     * WORD LOADS
     * ------------------------------------------------------------
     */

    a = mem32[0];
    b = mem32[1];

    sink = a ^ b;

    a = mem32[2];
    b = mem32[3];

    sink = a ^ b;

    a = mem32[4];
    b = mem32[5];

    sink = a ^ b;

    /*
     * ------------------------------------------------------------
     * HALF-WORD STORES
     * ------------------------------------------------------------
     */

    mem16[0] = 0x0000;
    mem16[1] = 0xFFFF;
    mem16[2] = 0xAAAA;
    mem16[3] = 0x5555;
    mem16[4] = 0x1234;
    mem16[5] = 0xFEDC;

    /*
     * HALF-WORD LOADS
     * ------------------------------------------------------------
     */

    a = mem16[0];
    b = mem16[1];

    sink = a ^ b;

    a = mem16[2];
    b = mem16[3];

    sink = a ^ b;

    /*
     * ------------------------------------------------------------
     * BYTE STORES
     * ------------------------------------------------------------
     */

    mem8[0] = 0x00;
    mem8[1] = 0xFF;
    mem8[2] = 0xAA;
    mem8[3] = 0x55;

    mem8[4] = 0x12;
    mem8[5] = 0x34;
    mem8[6] = 0x56;
    mem8[7] = 0x78;

    /*
     * ------------------------------------------------------------
     * BYTE LOADS
     * ------------------------------------------------------------
     */

    a = mem8[0];
    b = mem8[1];

    sink = a ^ b;

    a = mem8[2];
    b = mem8[3];

    sink = a ^ b;

    a = mem8[4];
    b = mem8[5];

    sink = a ^ b;

    a = mem8[6];
    b = mem8[7];

    sink = a ^ b;

    /*
     * ------------------------------------------------------------
     * Repeated separated accesses
     * ------------------------------------------------------------
     */

    mem32[20] = 0x11111111;
    a = mem32[20];

    mem32[30] = 0x22222222;
    b = mem32[30];

    mem32[40] = 0x33333333;
    a ^= mem32[40];

    mem32[50] = 0x44444444;
    b ^= mem32[50];

    sink = a ^ b;

    /*
     * ------------------------------------------------------------
     * PASS
     * ------------------------------------------------------------
     */

    test_pass();

    while (1)
        asm volatile("nop");

    return 0;
}