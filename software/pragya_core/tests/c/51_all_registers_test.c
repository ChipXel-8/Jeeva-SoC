#include "pragya_test.h"
#include <stdint.h>

volatile int r[32];

volatile int sum;

int main(void)
{
    /*------------------------------------------
      Initialize Every Register Variable
    ------------------------------------------*/

    r[0]=0;
    r[1]=1;
    r[2]=2;
    r[3]=3;
    r[4]=4;
    r[5]=5;
    r[6]=6;
    r[7]=7;
    r[8]=8;
    r[9]=9;
    r[10]=10;
    r[11]=11;
    r[12]=12;
    r[13]=13;
    r[14]=14;
    r[15]=15;
    r[16]=16;
    r[17]=17;
    r[18]=18;
    r[19]=19;
    r[20]=20;
    r[21]=21;
    r[22]=22;
    r[23]=23;
    r[24]=24;
    r[25]=25;
    r[26]=26;
    r[27]=27;
    r[28]=28;
    r[29]=29;
    r[30]=30;
    r[31]=31;

    /*------------------------------------------
      RAW Dependency Across Every Register
    ------------------------------------------*/

    for(int i=1;i<31;i++)
        r[i+1]=r[i]+r[i-1];

    /*------------------------------------------
      ALU Operations
    ------------------------------------------*/

    for(int i=1;i<31;i++)
    {
        r[i]=r[i]+5;
        r[i]=r[i]-3;
        r[i]=r[i]^0x55;
        r[i]=r[i]|0xAA;
        r[i]=r[i]&0xFF;
    }

    /*------------------------------------------
      Shift Operations
    ------------------------------------------*/

    for(int i=1;i<31;i++)
    {
        r[i]=r[i]<<1;
        r[i]=r[i]>>1;
    }

    /*------------------------------------------
      Multiply / Divide / Remainder
    ------------------------------------------*/

    for(int i=1;i<30;i++)
    {
        r[i]=r[i]*3;
        r[i]=r[i]/3;
        r[i]=r[i]%17;
    }

    /*------------------------------------------
      Long Forwarding Chain
    ------------------------------------------*/

    for(int i=1;i<25;i++)
    {
        r[i+1]=r[i]+10;
        r[i+2]=r[i+1]+20;
        r[i+3]=r[i+2]+30;
    }

    /*------------------------------------------
      Accumulate
    ------------------------------------------*/

    sum=0;

    for(int i=1;i<32;i++)
        sum+=r[i];

    if(sum==0)
        test_fail();

    /*------------------------------------------
      Reverse Dependency
    ------------------------------------------*/

    for(int i=30;i>0;i--)
        r[i]=r[i+1]+r[i];

    sum=0;

    for(int i=1;i<32;i++)
        sum+=r[i];

    if(sum==0)
        test_fail();

    test_pass();

    return 0;
}
