#include "pragya_test.h"
#include <stdint.h>

/*
 * ============================================================
 * cross_memory_rs1_002
 *
 * Goal:
 *
 *     Cover memory instruction × RS1 = X3
 *
 * Required combinations:
 *
 *     LB  × X3
 *     LH  × X3
 *     LW  × X3
 *     LBU × X3
 *     LHU × X3
 *
 *     SB  × X3
 *     SH  × X3
 *     SW  × X3
 *
 * X0 combinations are intentionally NOT generated because
 * address 0x00000000 is outside the valid data-memory region
 * used by the test environment.
 *
 * ============================================================
 */

volatile uint32_t mem_test[16];


int main(void)
{
    /*
     * ========================================================
     * Initialize memory
     * ========================================================
     */

    mem_test[0] = 0x12345678;
    mem_test[1] = 0xAABBCCDD;
    mem_test[2] = 0x11223344;
    mem_test[3] = 0x55667788;


    /*
     * ========================================================
     * X3 = valid data-memory address
     * ========================================================
     *
     * All memory instructions below therefore have:
     *
     *                 rs1 = X3
     *
     * Use explicit assembly so the compiler cannot change
     * the source register.
     * ========================================================
     */

    asm volatile(
        /*
         * ----------------------------------------------------
         * Load address into X3
         * ----------------------------------------------------
         */

        "la x3, mem_test\n"

        /*
         * ----------------------------------------------------
         * LB × X3
         * ----------------------------------------------------
         */

        "lb  x0, 0(x3)\n"

        /*
         * ----------------------------------------------------
         * LH × X3
         * ----------------------------------------------------
         */

        "lh  x0, 0(x3)\n"

        /*
         * ----------------------------------------------------
         * LW × X3
         * ----------------------------------------------------
         */

        "lw  x0, 0(x3)\n"

        /*
         * ----------------------------------------------------
         * LBU × X3
         * ----------------------------------------------------
         */

        "lbu x0, 0(x3)\n"

        /*
         * ----------------------------------------------------
         * LHU × X3
         * ----------------------------------------------------
         */

        "lhu x0, 0(x3)\n"

        /*
         * ----------------------------------------------------
         * SB × X3
         * ----------------------------------------------------
         *
         * Store zero. Only RS1 is important for this cross.
         * ----------------------------------------------------
         */

        "sb  x0, 8(x3)\n"

        /*
         * ----------------------------------------------------
         * SH × X3
         * ----------------------------------------------------
         */

        "sh  x0, 10(x3)\n"

        /*
         * ----------------------------------------------------
         * SW × X3
         * ----------------------------------------------------
         */

        "sw  x0, 12(x3)\n"

        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * PASS
     * ========================================================
     */

    test_pass();

    return 0;
}