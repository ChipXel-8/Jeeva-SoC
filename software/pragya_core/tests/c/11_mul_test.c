#include "pragya_test.h"
#include <stdint.h>

volatile int32_t a, b;
volatile int32_t result;

int main(void)
{
    /*-----------------------------------------
      Positive × Positive
    -----------------------------------------*/

    a = 10;
    b = 20;

    result = a * b;

    if(result != 200)
        test_fail();

    /*-----------------------------------------
      Positive × Negative
    -----------------------------------------*/

    a = 10;
    b = -20;

    result = a * b;

    if(result != -200)
        test_fail();

    /*-----------------------------------------
      Negative × Positive
    -----------------------------------------*/

    a = -10;
    b = 20;

    result = a * b;

    if(result != -200)
        test_fail();

    /*-----------------------------------------
      Negative × Negative
    -----------------------------------------*/

    a = -10;
    b = -20;

    result = a * b;

    if(result != 200)
        test_fail();

    /*-----------------------------------------
      Zero
    -----------------------------------------*/

    a = 0;
    b = 12345;

    result = a * b;

    if(result != 0)
        test_fail();

    /*-----------------------------------------
      One
    -----------------------------------------*/

    a = 1;
    b = 54321;

    result = a * b;

    if(result != 54321)
        test_fail();

    /*-----------------------------------------
      Minus One
    -----------------------------------------*/

    a = -1;
    b = 54321;

    result = a * b;

    if(result != -54321)
        test_fail();

    /*-----------------------------------------
      Large Numbers
    -----------------------------------------*/

    a = 1234;
    b = 5678;

    result = a * b;

    if(result != 7006652)
        test_fail();

    /*-----------------------------------------
      Powers of Two
    -----------------------------------------*/

    a = 1024;
    b = 2048;

    result = a * b;

    if(result != 2097152)
        test_fail();

    /*-----------------------------------------
      Accumulated Multiply
    -----------------------------------------*/

    result = 1;

    for(int i = 1; i <= 6; i++)
        result *= i;

    if(result != 720)
        test_fail();

    test_pass();

    return 0;
}