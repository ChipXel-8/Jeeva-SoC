#include "pragya_test.h"
#include <stdint.h>

volatile int mem[64];

volatile int a,b,c,d,e,f,g,h,i,j,k,l;
volatile int sum;

int main(void)
{
    /*------------------------------------------
      Initialize Memory
    ------------------------------------------*/

    for(int x=0;x<64;x++)
        mem[x]=x+1;

    /*------------------------------------------
      EX -> EX Forwarding Chain
    ------------------------------------------*/

    a=10;
    b=a+5;
    c=b+6;
    d=c+7;
    e=d+8;
    f=e+9;

    if(f!=45)
        test_fail();

    /*------------------------------------------
      Dual Source Forwarding
    ------------------------------------------*/

    a=100;
    b=50;
    c=a+b;
    d=c+a;
    e=d+b;
    f=e+c;

    if(f!=450)
        test_fail();

    /*------------------------------------------
      Long Dependency Chain
    ------------------------------------------*/

    a=1;

    for(int x=0;x<40;x++)
        a=a+x;

    if(a!=781)
        test_fail();

    /*------------------------------------------
      Load -> Use Hazard
    ------------------------------------------*/

    a=mem[5];
    b=a+1;
    c=b+2;
    d=c+3;
    e=d+4;

    if(e!=16)
        test_fail();

    /*------------------------------------------
      Store -> Load Hazard
    ------------------------------------------*/

    mem[20]=555;

    a=mem[20];
    b=a+1;

    if(b!=556)
        test_fail();

    /*------------------------------------------
      Branch Dependency
    ------------------------------------------*/

    a=0;

    for(int x=0;x<20;x++)
    {
        a++;

        if(a&1)
            b=a+10;
        else
            b=a-10;

        c=b+5;
    }

    if(a!=20)
        test_fail();

    /*------------------------------------------
      Multiply Forwarding
    ------------------------------------------*/

    a=7;
    b=9;

    c=a*b;
    d=c+10;
    e=d*2;
    f=e-5;

    if(f!=141)
        test_fail();

    /*------------------------------------------
      Divide Forwarding
    ------------------------------------------*/

    a=300;
    b=7;

    c=a/b;
    d=c+10;
    e=d*3;

    if(e!=156)
        test_fail();

    /*------------------------------------------
      Remainder Forwarding
    ------------------------------------------*/

    a=123;
    b=10;

    c=a%b;
    d=c+100;
    e=d*2;

    if(e!=206)
        test_fail();

    /*------------------------------------------
      Mixed ALU Forwarding
    ------------------------------------------*/

    a=0x1234;
    b=0x5678;

    c=a^b;
    d=c|a;
    e=d&0xFFFF;
    f=e<<3;
    g=f>>2;

    if(g!=(((((0x1234^0x5678)|0x1234)&0xFFFF)<<3)>>2))
        test_fail();

    /*------------------------------------------
      Back-to-Back Forwarding
    ------------------------------------------*/

    a=5;

    for(int x=0;x<50;x++)
    {
        a=a+1;
        a=a*2;
        a=a-3;
        a=a^x;
    }

    if(a==0)
        test_fail();

    /*------------------------------------------
      Mixed Memory + ALU
    ------------------------------------------*/

    mem[40]=100;

    a=mem[40];
    b=a+10;
    mem[41]=b;
    c=mem[41];
    d=c*2;
    mem[42]=d;
    e=mem[42];

    if(e!=220)
        test_fail();

    test_pass();

    return 0;
}
