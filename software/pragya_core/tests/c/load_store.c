volatile uint32_t a,b,c,d,e,f,g,h;

int main(void)
{
    //--------------------------------------------------
    // Byte Stores
    //--------------------------------------------------

    mem8[0] = 0x12;
    mem8[1] = 0x80;
    mem8[2] = 0xFF;

    //--------------------------------------------------
    // Halfword Stores
    //--------------------------------------------------

    mem16[0] = 0x1234;
    mem16[1] = 0x8001;
    mem16[2] = 0xFFFF;

    //--------------------------------------------------
    // Word Stores
    //--------------------------------------------------

    mem32[0] = 0x12345678;
    mem32[1] = 0x80000001;
    mem32[2] = 0xFFFFFFFF;

    //--------------------------------------------------
    // LB
    //--------------------------------------------------

    a = *(volatile int8_t *)&mem8[0];
    b = *(volatile int8_t *)&mem8[1];
    c = *(volatile int8_t *)&mem8[2];

    //--------------------------------------------------
    // LBU
    //--------------------------------------------------

    d = *(volatile uint8_t *)&mem8[0];
    e = *(volatile uint8_t *)&mem8[1];
    f = *(volatile uint8_t *)&mem8[2];

    //--------------------------------------------------
    // LH
    //--------------------------------------------------

    a = *(volatile int16_t *)&mem16[0];
    b = *(volatile int16_t *)&mem16[1];
    c = *(volatile int16_t *)&mem16[2];

    //--------------------------------------------------
    // LHU
    //--------------------------------------------------

    d = *(volatile uint16_t *)&mem16[0];
    e = *(volatile uint16_t *)&mem16[1];
    f = *(volatile uint16_t *)&mem16[2];

    //--------------------------------------------------
    // LW
    //--------------------------------------------------

    g = mem32[0];
    h = mem32[1];
    a = mem32[2];

    //--------------------------------------------------
    // RAW hazards
    //--------------------------------------------------

    mem32[10] = 55;
    b = mem32[10];
    mem32[10] = b + 1;
    c = mem32[10];

    mem16[20] = 0x5678;
    d = *(volatile uint16_t *)&mem16[20];

    mem8[30] = 0xAB;
    e = *(volatile uint8_t *)&mem8[30];

    //--------------------------------------------------
    // Verification
    //--------------------------------------------------

    if(c != 56)
        test_fail();

    if(d != 0x5678)
        test_fail();

    if(e != 0xAB)
        test_fail();

    test_pass();

    return 0;
}
