#include "pragya_test.h"
#include <stdint.h>

volatile int mem[128];

volatile int a,b,c,d,e,f,g,h,i,j;
volatile int sum;

int main(void)
{
    /*------------------------------------------
      Initialize Memory
    ------------------------------------------*/

    for(int k=0;k<128;k++)
        mem[k]=k*5+1;

    /*------------------------------------------
      Long RAW Dependency
    ------------------------------------------*/

    a=1;
    b=a+2;
    c=b+3;
    d=c+4;
    e=d+5;
    f=e+6;
    g=f+7;
    h=g+8;
    i=h+9;
    j=i+10;

    if(j!=55)
        test_fail();

    /*------------------------------------------
      Dual Forwarding
    ------------------------------------------*/

    a=10;
    b=20;

    c=a+b;
    d=c+a;
    e=d+b;
    f=e+c;

    if(f!=100)
        test_fail();

    /*------------------------------------------
      Load-Use Hazard
    ------------------------------------------*/

    a=mem[20];
    b=a+1;
    c=b+2;
    d=c+3;

    if(d!=107)
        test_fail();

    /*------------------------------------------
      Store -> Load Hazard
    ------------------------------------------*/

    mem[30]=777;

    a=mem[30];

    if(a!=777)
        test_fail();

    /*------------------------------------------
      Mixed ALU Hazard
    ------------------------------------------*/

    a=5;

    for(int k=0;k<20;k++)
    {
        a=a+k;
        a=a^k;
        a=a+3;
        a=a-1;
    }

    if(a==0)
        test_fail();

    /*------------------------------------------
      Multiply/Divide Dependency
    ------------------------------------------*/

    a=50;

    b=a*3;
    c=b/5;
    d=c%7;
    e=d*11;
    f=e/2;

    if(f!=11)
        test_fail();

    /*------------------------------------------
      Consecutive Loads
    ------------------------------------------*/

    sum=0;

    for(int k=0;k<32;k++)
        sum+=mem[k];

    if(sum==0)
        test_fail();

    /*------------------------------------------
      Consecutive Stores
    ------------------------------------------*/

    for(int k=0;k<32;k++)
        mem[k]=k;

    for(int k=0;k<32;k++)
    {
        if(mem[k]!=k)
            test_fail();
    }

    /*------------------------------------------
      Branch Hazard
    ------------------------------------------*/

    sum=0;

    for(int k=0;k<40;k++)
    {
        if(k&1)
            sum+=k;
        else
            sum-=k;
    }

    if(sum!=-20)
        test_fail();

    /*------------------------------------------
      Pipeline Stress Loop
    ------------------------------------------*/

    a=1;

    for(int k=0;k<100;k++)
    {
        a=a+k;
        a=a<<1;
        a=a>>1;
        a=a^k;
    }

    if(a==0)
        test_fail();

    test_pass();

    return 0;
}
