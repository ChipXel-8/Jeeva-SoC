#include "pragya_test.h"
#include <stdint.h>

volatile uint8_t  mem8[64];
volatile uint16_t mem16[64];
volatile uint32_t mem32[64];

volatile int a,b,c,d,e,f,g,h;

int main(void)
{
    /*------------------------------------------
      Initialize Memories
    ------------------------------------------*/

    for(int i=0;i<64;i++)
    {
        mem8[i]  = i;
        mem16[i] = i*10;
        mem32[i] = i*100;
    }

    /*------------------------------------------
      Store Byte
    ------------------------------------------*/

    mem8[0] = 0x12;
    mem8[1] = 0x80;
    mem8[2] = 0xFF;

    /*------------------------------------------
      Load Byte
    ------------------------------------------*/

    a = (int8_t)mem8[0];
    b = (int8_t)mem8[1];
    c = (int8_t)mem8[2];

    if(a != 0x12) test_fail();
    if(b != -128) test_fail();
    if(c != -1) test_fail();

    /*------------------------------------------
      Load Unsigned Byte
    ------------------------------------------*/

    d = mem8[1];
    e = mem8[2];

    if(d != 128) test_fail();
    if(e != 255) test_fail();

    /*------------------------------------------
      Store Half
    ------------------------------------------*/

    mem16[0]=0x1234;
    mem16[1]=0x8000;
    mem16[2]=0xFFFF;

    /*------------------------------------------
      Load Half
    ------------------------------------------*/

    a=(int16_t)mem16[0];
    b=(int16_t)mem16[1];
    c=(int16_t)mem16[2];

    if(a!=0x1234) test_fail();
    if(b!=-32768) test_fail();
    if(c!=-1) test_fail();

    /*------------------------------------------
      Load Unsigned Half
    ------------------------------------------*/

    d=mem16[1];
    e=mem16[2];

    if(d!=32768) test_fail();
    if(e!=65535) test_fail();

    /*------------------------------------------
      Store Word
    ------------------------------------------*/

    mem32[0]=0x12345678;
    mem32[1]=0xFFFFFFFF;
    mem32[2]=0x80000000;

    /*------------------------------------------
      Load Word
    ------------------------------------------*/

    if(mem32[0]!=0x12345678) test_fail();
    if(mem32[1]!=0xFFFFFFFF) test_fail();
    if(mem32[2]!=0x80000000) test_fail();

    /*------------------------------------------
      Store -> Load Hazard
    ------------------------------------------*/

    mem32[10]=555;
    a=mem32[10];

    if(a!=555)
        test_fail();

    /*------------------------------------------
      Load -> ALU Hazard
    ------------------------------------------*/

    a=mem32[5];
    b=a+1;
    c=b+2;
    d=c+3;

    if(d!=506)
        test_fail();

    /*------------------------------------------
      Sequential Stores
    ------------------------------------------*/

    for(int i=0;i<32;i++)
        mem32[i]=i*7;

    /*------------------------------------------
      Sequential Loads
    ------------------------------------------*/

    for(int i=0;i<32;i++)
    {
        if(mem32[i]!=(uint32_t)(i*7))
            test_fail();
    }

    /*------------------------------------------
      Mixed Accesses
    ------------------------------------------*/

    mem8[10]=0xAA;
    mem16[10]=0xBBBB;
    mem32[10]=0xCCCCDDDD;

    a=mem8[10];
    b=mem16[10];
    c=mem32[10];

    if(a!=0xAA) test_fail();
    if(b!=0xBBBB) test_fail();
    if(c!=0xCCCCDDDD) test_fail();

    test_pass();

    return 0;
}
