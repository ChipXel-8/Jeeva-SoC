#include "pragya_test.h"
#include <stdint.h>

volatile int32_t  s;
volatile uint32_t u;
volatile uint32_t result;

int main(void)
{
    /*------------------------------------------
      ADDI
    ------------------------------------------*/

    s = 100;

    if ((s + 20) != 120)
        test_fail();

    if ((s - 50) != 50)
        test_fail();

    if ((s + 0) != 100)
        test_fail();

    if ((s - 100) != 0)
        test_fail();

    /*------------------------------------------
      ANDI
    ------------------------------------------*/

    u = 0xFF55;

    result = u & 0x0F0F;

    if (result != 0x0F05)
        test_fail();

    /*------------------------------------------
      ORI
    ------------------------------------------*/

    result = u | 0x00AA;

    if (result != 0xFFFF)
        test_fail();

    /*------------------------------------------
      XORI
    ------------------------------------------*/

    result = 0xAAAA ^ 0x5555;

    if (result != 0xFFFF)
        test_fail();

    /*------------------------------------------
      SLTI
    ------------------------------------------*/

    s = -5;

    if (!(s < 0))
        test_fail();

    if (!(s < 10))
        test_fail();

    if (s < -10)
        test_fail();

    /*------------------------------------------
      SLTIU
    ------------------------------------------*/

    u = 5;

    if (!(u < 6))
        test_fail();

    if (u < 5)
        test_fail();

    /*------------------------------------------
      SLLI
    ------------------------------------------*/

    result = 1;

    result <<= 10;

    if (result != 1024)
        test_fail();

    /*------------------------------------------
      SRLI
    ------------------------------------------*/

    result >>= 5;

    if (result != 32)
        test_fail();

    /*------------------------------------------
      SRAI
    ------------------------------------------*/

    s = -64;

    s >>= 3;

    if (s != -8)
        test_fail();

    /*------------------------------------------
      Immediate Boundaries
    ------------------------------------------*/

    s = 2047;

    if (s != 2047)
        test_fail();

    s = -2048;

    if (s != -2048)
        test_fail();

    test_pass();

    return 0;
}
