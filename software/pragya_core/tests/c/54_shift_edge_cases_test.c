#include "pragya_test.h"
#include <stdint.h>

volatile int a,b,c,d,e,f,g,h;
volatile unsigned ua,ub;

int main(void)
{
    /*------------------------------------------
      Logical Left Shift
    ------------------------------------------*/

    a = 1;

    b = a << 1;
    c = b << 2;
    d = c << 5;

    if(b != 2) test_fail();
    if(c != 8) test_fail();
    if(d != 256) test_fail();

    /*------------------------------------------
      Shift Amount = 0
    ------------------------------------------*/

    a = 12345;

    b = a << 0;
    c = a >> 0;

    if(b != a) test_fail();
    if(c != a) test_fail();

    /*------------------------------------------
      Shift Amount = 31
    ------------------------------------------*/

    ua = 1;

    ub = ua << 31;

    if(ub != 0x80000000u)
        test_fail();

    /*------------------------------------------
      Logical Right Shift
    ------------------------------------------*/

    ua = 0x80000000u;

    b = ua >> 1;

    if((unsigned)b != 0x40000000u)
        test_fail();

    /*------------------------------------------
      Arithmetic Right Shift
    ------------------------------------------*/

    a = -16;

    b = a >> 1;
    c = b >> 2;

    if(b != -8)
        test_fail();

    if(c != -2)
        test_fail();

    /*------------------------------------------
      Positive Arithmetic Shift
    ------------------------------------------*/

    a = 64;

    b = a >> 3;

    if(b != 8)
        test_fail();

    /*------------------------------------------
      RAW Dependency Chain
    ------------------------------------------*/

    a = 5;

    b = a << 2;
    c = b >> 1;
    d = c << 3;
    e = d >> 2;

    if(e != 20)
        test_fail();

    /*------------------------------------------
      Mixed Shift Operations
    ------------------------------------------*/

    a = 0x12345678;

    b = a << 4;
    c = b >> 4;

    if(c != 0x02345678)
        test_fail();

    /*------------------------------------------
      Shift Stress Loop
    ------------------------------------------*/

    a = 1;

    for(int i=0;i<20;i++)
    {
        a <<= 1;
        a >>= 1;
        a <<= 2;
        a >>= 2;
    }

    if(a != 1)
        test_fail();

    /*------------------------------------------
      Forwarding Test
    ------------------------------------------*/

    a = 7;

    b = a << 3;
    c = b + 10;
    d = c >> 1;
    e = d - 5;
    f = e << 2;

    if(f != 132)
        test_fail();

    /*------------------------------------------
      Variable Shift Amount
    ------------------------------------------*/

    a = 3;

    for(int i=0;i<5;i++)
        a <<= i;

    if(a == 0)
        test_fail();

    /*------------------------------------------
      Alternating Shifts
    ------------------------------------------*/

    a = -256;

    b = a >> 4;
    c = b << 4;

    if(c != -256)
        test_fail();

    test_pass();

    return 0;
}
