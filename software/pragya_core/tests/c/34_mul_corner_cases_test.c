#include "pragya_test.h"
#include <stdint.h>

volatile int a,b,c;

int main(void)
{
    /*------------------------------------------
      MUL with ZERO
    ------------------------------------------*/

    a = 0;
    b = 12345;
    c = a * b;

    if(c != 0)
        test_fail();

    /*------------------------------------------
      MUL with ONE
    ------------------------------------------*/

    a = 1;
    b = 5678;
    c = a * b;

    if(c != 5678)
        test_fail();

    /*------------------------------------------
      MUL with NEGATIVE ONE
    ------------------------------------------*/

    a = -1;
    b = 100;

    c = a * b;

    if(c != -100)
        test_fail();

    /*------------------------------------------
      MAX POSITIVE
    ------------------------------------------*/

    a = 0x7fffffff;
    b = 1;

    c = a * b;

    if(c != 0x7fffffff)
        test_fail();

    /*------------------------------------------
      MAX NEGATIVE
    ------------------------------------------*/

    a = 0x80000000;
    b = 1;

    c = a * b;

    if(c != (int)0x80000000)
        test_fail();

    /*------------------------------------------
      Power of Two
    ------------------------------------------*/

    a = 1024;
    b = 16;

    c = a * b;

    if(c != 16384)
        test_fail();

    /*------------------------------------------
      Normal Numbers
    ------------------------------------------*/

    a = 37;
    b = 91;

    c = a * b;

    if(c != 3367)
        test_fail();

    /*------------------------------------------
      RAW Dependency
    ------------------------------------------*/

    a = 9;
    b = a * 3;
    c = b * 5;

    if(c != 135)
        test_fail();

    /*------------------------------------------
      Consecutive MULs
    ------------------------------------------*/

    a = 2;

    for(int i=1;i<=10;i++)
    {
        a = a * i;
    }

    if(a != 7257600)
        test_fail();

    /*------------------------------------------
      Mixed Operands
    ------------------------------------------*/

    a = -200;
    b = 300;

    c = a * b;

    if(c != -60000)
        test_fail();

    test_pass();

    return 0;
}
