#include "pragya_test.h"
#include <stdint.h>

volatile int mem[32];

volatile int a,b,c,d,e,f,g,h,i,j;
volatile int sum;

int main(void)
{
    /*------------------------------------------
      Initialize Memory
    ------------------------------------------*/

    for(int k=0;k<32;k++)
        mem[k]=k+1;

    /*------------------------------------------
      RAW Dependency Chain
    ------------------------------------------*/

    a=10;
    b=a+5;
    c=b+10;
    d=c-3;
    e=d*2;
    f=e/3;
    g=f%5;
    h=g+100;
    i=h<<2;
    j=i>>1;

    if(j!=((( (( ( ((10+5)+10)-3 )*2)/3)%5)+100)<<2)>>1)
        test_fail();

    /*------------------------------------------
      Load-Use Hazards
    ------------------------------------------*/

    a=mem[5];
    b=a+1;
    c=b+2;
    d=c+3;

    if(d!=12)
        test_fail();

    /*------------------------------------------
      Store-Load Dependency
    ------------------------------------------*/

    mem[10]=555;

    a=mem[10];

    if(a!=555)
        test_fail();

    /*------------------------------------------
      Branch Stress
    ------------------------------------------*/

    sum=0;

    for(int k=0;k<20;k++)
    {
        if(k&1)
            sum+=k;
        else
            sum-=k;
    }

    if(sum!= 10)
        test_fail();

    /*------------------------------------------
      Nested Loops
    ------------------------------------------*/

    sum=0;

    for(int i=0;i<8;i++)
    {
        for(int j=0;j<8;j++)
        {
            sum+=i*j;
        }
    }

    if(sum!=784)
        test_fail();

    /*------------------------------------------
      Register Dependency Chain
    ------------------------------------------*/

    a=1;

    for(int i=0;i<20;i++)
        a=a+i;

    if(a!=191)
        test_fail();

    /*------------------------------------------
      Memory Stress
    ------------------------------------------*/

    for(int i=0;i<16;i++)
        mem[i]=i*3;

    for(int i=0;i<16;i++)
    {
        if(mem[i]!=i*3)
            test_fail();
    }

    /*------------------------------------------
      Mixed ALU Operations
    ------------------------------------------*/

    a=100;
    b=35;

    c=a+b;
    d=c-b;
    e=d*b;
    f=e/7;
    g=f%11;
    h=g^0x55;
    i=h|0xAA;
    j=i&0xFF;

    if(j!=((((((100+35)-35)*35)/7)%11)^0x55|0xAA)&0xFF)
        test_fail();

    /*------------------------------------------
      Pipeline Dependency Loop
    ------------------------------------------*/

    a=1;

    for(int i=0;i<50;i++)
    {
        a=a+i;
        a=a^i;
        a=a+3;
        a=a-2;
    }

    if(a==0)
        test_fail();

    test_pass();

    return 0;
}
