#include "pragya_test.h"
#include <stdint.h>

volatile uint32_t sink;

int main(void)
{
    volatile uint32_t *mem =
        (volatile uint32_t *)0x80008020;

    uint32_t value;

    /*
     * ============================================================
     * OBI / MEMORY REQUEST TEST
     * ============================================================
     *
     * Exercise:
     *   - store request
     *   - load request
     *   - consecutive memory operations
     *   - different data patterns
     *   - load response / rvalid path
     */

    /* ------------------------------------------------------------
     * STORE 1
     * ------------------------------------------------------------ */
    mem[0] = 0xAAAAAAAA;

    /* ------------------------------------------------------------
     * LOAD 1
     * ------------------------------------------------------------ */
    value = mem[0];

    sink = value;


    /* ------------------------------------------------------------
     * STORE 2
     * ------------------------------------------------------------ */
    mem[1] = 0x55555555;

    /* ------------------------------------------------------------
     * LOAD 2
     * ------------------------------------------------------------ */
    value = mem[1];

    sink = value;


    /* ------------------------------------------------------------
     * STORE 3
     * ------------------------------------------------------------ */
    mem[2] = 0xFFFFFFFF;

    /* ------------------------------------------------------------
     * LOAD 3
     * ------------------------------------------------------------ */
    value = mem[2];

    sink = value;


    /* ------------------------------------------------------------
     * STORE 4
     * ------------------------------------------------------------ */
    mem[3] = 0x00000000;

    /* ------------------------------------------------------------
     * LOAD 4
     * ------------------------------------------------------------ */
    value = mem[3];

    sink = value;


    /*
     * Consecutive STORE -> LOAD operations.
     * This is useful for exercising the memory request/response
     * path repeatedly.
     */
    mem[4] = 0x12345678;
    value = mem[4];

    mem[5] = 0x87654321;
    value = mem[5];

    mem[6] = 0xAAAAAAAA;
    value = mem[6];

    mem[7] = 0x55555555;
    value = mem[7];


    /*
     * Prevent compiler from removing memory accesses.
     */
    sink = value;


    /*
     * ============================================================
     * PASS
     * ============================================================
     */
    test_pass();

    while (1)
        asm volatile("nop");

    return 0;
}