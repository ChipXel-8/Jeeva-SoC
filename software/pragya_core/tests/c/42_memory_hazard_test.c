#include "pragya_test.h"
#include <stdint.h>

volatile int mem[64];

volatile int a,b,c,d,e,f,g,h;
volatile int sum;

int main(void)
{
    /*------------------------------------------
      Initialize Memory
    ------------------------------------------*/

    for(int i=0;i<64;i++)
        mem[i]=i;

    /*------------------------------------------
      Store -> Immediate Load
    ------------------------------------------*/

    mem[0]=111;
    a=mem[0];

    if(a!=111)
        test_fail();

    /*------------------------------------------
      Load -> Use Hazard
    ------------------------------------------*/

    a=mem[5];
    b=a+10;
    c=b+20;
    d=c+30;

    if(d!=65)
        test_fail();

    /*------------------------------------------
      Consecutive Loads
    ------------------------------------------*/

    a=mem[1];
    b=mem[2];
    c=mem[3];
    d=mem[4];
    e=mem[5];

    if((a+b+c+d+e)!=15)
        test_fail();

    /*------------------------------------------
      Consecutive Stores
    ------------------------------------------*/

    mem[10]=100;
    mem[11]=200;
    mem[12]=300;
    mem[13]=400;

    if(mem[10]!=100) test_fail();
    if(mem[11]!=200) test_fail();
    if(mem[12]!=300) test_fail();
    if(mem[13]!=400) test_fail();

    /*------------------------------------------
      Store -> Load Chain
    ------------------------------------------*/

    mem[20]=500;
    a=mem[20];
    b=a+1;
    mem[21]=b;
    c=mem[21];
    d=c+2;

    if(d!=503)
        test_fail();

    /*------------------------------------------
      Address Dependency
    ------------------------------------------*/

    a=8;
    mem[a]=888;
    b=mem[a];

    if(b!=888)
        test_fail();

    /*------------------------------------------
      Sliding Window Loads
    ------------------------------------------*/

    sum=0;

    for(int i=0;i<20;i++)
    {
        sum+=mem[i];
    }

    if(sum!=1800)
        test_fail();

    /*------------------------------------------
      RAW Dependency Chain
    ------------------------------------------*/

    mem[30]=1;

    for(int i=0;i<20;i++)
    {
        mem[30]=mem[30]+i;
    }

    if(mem[30]!=191)
        test_fail();

    /*------------------------------------------
      Store Every Entry
    ------------------------------------------*/

    for(int i=0;i<32;i++)
        mem[i]=i*7;

    /*------------------------------------------
      Load Every Entry
    ------------------------------------------*/

    for(int i=0;i<32;i++)
    {
        if(mem[i]!=(i*7))
            test_fail();
    }

    /*------------------------------------------
      Back-to-Back Memory Hazards
    ------------------------------------------*/

    mem[40]=1000;
    a=mem[40];
    mem[41]=a+10;
    b=mem[41];
    mem[42]=b+10;
    c=mem[42];

    if(c!=1020)
        test_fail();

    /*------------------------------------------
      Mixed Memory Dependencies
    ------------------------------------------*/

    mem[50]=55;

    a=mem[50];
    b=a*2;
    mem[51]=b;

    c=mem[51];
    d=c+5;

    mem[52]=d;

    if(mem[52]!=115)
        test_fail();

    test_pass();

    return 0;
}
