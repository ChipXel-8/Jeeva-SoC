#include "pragya_test.h"
#include <stdint.h>

/*
 * ============================================================
 * CROSS INSTRUCTION × REGISTER WRITE TEST
 * ============================================================
 *
 * Goal:
 *
 *     Cover:
 *
 *     instruction × NO_WRITE
 *
 * where:
 *
 *     rd = x0
 *
 * Expected:
 *
 *     rd_we = 0
 *
 *
 * Missing bins:
 *
 *     ADD   × NO_WRITE
 *     SUB   × NO_WRITE
 *     SLL   × NO_WRITE
 *     SLT   × NO_WRITE
 *     SLTU  × NO_WRITE
 *     XOR   × NO_WRITE
 *     SRL   × NO_WRITE
 *     SRA   × NO_WRITE
 *     OR    × NO_WRITE
 *     AND   × NO_WRITE
 *
 *     ADDI  × NO_WRITE
 *     SLTI  × NO_WRITE
 *     SLTIU × NO_WRITE
 *     XORI  × NO_WRITE
 *     ORI   × NO_WRITE
 *     ANDI  × NO_WRITE
 *     SLLI  × NO_WRITE
 *     SRLI  × NO_WRITE
 *     SRAI  × NO_WRITE
 *
 *     LUI   × NO_WRITE
 *     AUIPC × NO_WRITE
 *
 *     JAL   × NO_WRITE
 *     JALR  × NO_WRITE
 *
 * ============================================================
 */


/* ============================================================
 * MAIN
 * ============================================================ */

int main(void)
{

    /*
     * ========================================================
     * SOURCE REGISTER SETUP
     * ========================================================
     *
     * x5  = 20
     * x6  = 5
     * x7  = 2
     *
     * These are used as source operands.
     *
     * Destination is always x0 for the instructions
     * whose coverage bin we want to hit.
     * ========================================================
     */

    asm volatile (

        "addi x5, x0, 20\n"
        "addi x6, x0, 5\n"
        "addi x7, x0, 2\n"

        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * R-TYPE
     * ========================================================
     */


    /*
     * --------------------------------------------------------
     * ADD × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "add x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SUB × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "sub x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SLL × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "sll x0, x5, x7\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SLT × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "slt x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SLTU × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "sltu x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * XOR × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "xor x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SRL × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "srl x0, x5, x7\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SRA × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "sra x0, x5, x7\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * OR × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "or x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * AND × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "and x0, x5, x6\n"
        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * I-TYPE ALU
     * ========================================================
     */


    /*
     * --------------------------------------------------------
     * ADDI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "addi x0, x5, 7\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SLTI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "slti x0, x5, 30\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SLTIU × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "sltiu x0, x5, 30\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * XORI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "xori x0, x5, 0x55\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * ORI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "ori x0, x5, 0x55\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * ANDI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "andi x0, x5, 0x0f\n"
        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * SHIFT IMMEDIATE
     * ========================================================
     */


    /*
     * --------------------------------------------------------
     * SLLI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "slli x0, x5, 3\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SRLI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "srli x0, x5, 2\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * SRAI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "srai x0, x5, 2\n"
        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * U-TYPE
     * ========================================================
     */


    /*
     * --------------------------------------------------------
     * LUI × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "lui x0, 0x12345\n"
        :
        :
        : "memory"
    );


    /*
     * --------------------------------------------------------
     * AUIPC × NO_WRITE
     * --------------------------------------------------------
     */

    asm volatile (
        "auipc x0, 0x1\n"
        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * JAL × NO_WRITE
     * ========================================================
     *
     * rd = x0
     *
     * Therefore:
     *
     *     rd_we = 0
     *
     * The instruction after JAL is skipped.
     * ========================================================
     */

    asm volatile (

        "jal x0, 1f\n"

        /*
         * This instruction must be skipped.
         */
        "addi x7, x0, 0\n"

        /*
         * JAL target.
         */
        "1:\n"

        "addi x7, x0, 1\n"

        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * JALR × NO_WRITE
     * ========================================================
     *
     * rd = x0
     *
     * rs1 = x5
     *
     * We first load the address of the target into x5.
     * ========================================================
     */

    asm volatile (

        "la x5, 1f\n"

        /*
         * JALR:
         *
         * rd  = x0
         * rs1 = x5
         * imm = 0
         *
         * Therefore:
         *
         *     rd_we = 0
         */
        "jalr x0, 0(x5)\n"

        /*
         * This instruction must be skipped.
         */
        "addi x7, x0, 0\n"

        /*
         * JALR target.
         */
        "1:\n"

        "addi x7, x0, 2\n"

        :
        :
        : "memory"
    );


    /*
     * ========================================================
     * PASS
     * ========================================================
     */

    test_pass();

    return 0;
}