#include "pragya_test.h"
#include <stdint.h>

volatile uint32_t mem[16];

volatile uint32_t a,b,c,d,e,f,g,h;

int main(void)
{
    /*------------------------------------------
      Initialize Memory
    ------------------------------------------*/

    mem[0] = 10;
    mem[1] = 20;
    mem[2] = 30;
    mem[3] = 40;
    mem[4] = 50;

    /*------------------------------------------
      LW -> ADD (Load-Use Hazard)
    ------------------------------------------*/

    a = mem[0];
    b = a + 5;

    if(b != 15)
        test_fail();

    /*------------------------------------------
      LW -> SUB
    ------------------------------------------*/

    c = mem[1];
    d = c - 10;

    if(d != 10)
        test_fail();

    /*------------------------------------------
      LW -> AND
    ------------------------------------------*/

    e = mem[2];
    f = e & 0x0F;

    if(f != (30 & 0x0F))
        test_fail();

    /*------------------------------------------
      LW -> OR
    ------------------------------------------*/

    g = mem[3];
    h = g | 0x100;

    if(h != (40 | 0x100))
        test_fail();

    /*------------------------------------------
      Consecutive Loads
    ------------------------------------------*/

    a = mem[4];
    b = mem[3];
    c = mem[2];
    d = mem[1];

    if(a != 50) test_fail();
    if(b != 40) test_fail();
    if(c != 30) test_fail();
    if(d != 20) test_fail();

    /*------------------------------------------
      Multiple RAW Hazards
    ------------------------------------------*/

    a = mem[0];
    b = a + 1;
    c = b + 1;
    d = c + 1;
    e = d + 1;
    f = e + 1;

    if(f != 15)
        test_fail();

    /*------------------------------------------
      Store then Load
    ------------------------------------------*/

    mem[5] = 1234;

    a = mem[5];

    if(a != 1234)
        test_fail();

    /*------------------------------------------
      Load After Store
    ------------------------------------------*/

    mem[6] = 777;

    b = mem[6];

    if(b != 777)
        test_fail();

    test_pass();

    return 0;
}