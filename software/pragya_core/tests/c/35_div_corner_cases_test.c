#include "pragya_test.h"
#include <stdint.h>

volatile int a,b,c,d;

int main(void)
{
    /*------------------------------------------
      Divide by One
    ------------------------------------------*/

    a = 500;
    b = 1;
    c = a / b;

    if(c != 500)
        test_fail();

    /*------------------------------------------
      Divide by Minus One
    ------------------------------------------*/

    a = 500;
    b = -1;
    c = a / b;

    if(c != -500)
        test_fail();

    /*------------------------------------------
      Negative Divide
    ------------------------------------------*/

    a = -500;
    b = 5;
    c = a / b;

    if(c != -100)
        test_fail();

    /*------------------------------------------
      Divide Two Negatives
    ------------------------------------------*/

    a = -500;
    b = -5;
    c = a / b;

    if(c != 100)
        test_fail();

    /*------------------------------------------
      Divide Zero
    ------------------------------------------*/

    a = 0;
    b = 55;
    c = a / b;

    if(c != 0)
        test_fail();

    /*------------------------------------------
      Divide by Zero
      (RV32M returns -1)
    ------------------------------------------*/

    a = 12345;
    b = 0;
    c = a / b;

    if(c != -1)
        test_fail();

    /*------------------------------------------
      Overflow
      INT_MIN / -1
    ------------------------------------------*/

    a = 0x80000000;
    b = -1;
    c = a / b;

    if(c != (int)0x80000000)
        test_fail();

    /*------------------------------------------
      Power-of-Two Divide
    ------------------------------------------*/

    a = 4096;
    b = 16;

    c = a / b;

    if(c != 256)
        test_fail();

    /*------------------------------------------
      RAW Dependency
    ------------------------------------------*/

    a = 1000;
    b = a / 10;
    c = b / 2;
    d = c / 5;

    if(d != 10)
        test_fail();

    /*------------------------------------------
      Consecutive Divide
    ------------------------------------------*/

    a = 1000000;

    for(int i=2;i<=6;i++)
        a = a / i;

    if(a != 1388)
        test_fail();

    test_pass();

    return 0;
}
