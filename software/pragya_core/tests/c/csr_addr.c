#include "pragya_test.h"
#include <stdint.h>

/*
 * ============================================================
 * CSR ADDRESS COVERAGE TEST
 *
 * Purpose:
 *   Cover missing CSR addresses:
 *
 *       INSTRET  = 0xC02
 *       CYCLEH   = 0xC80
 *
 * Coverage point:
 *
 *       cp_csr_addr
 *
 * ============================================================
 */


/* ============================================================
 * INSTRET READ
 *
 * CSR address = 0xC02
 * ============================================================ */

static inline uint32_t read_instret(void)
{
    uint32_t value;

    asm volatile (
        "csrr %0, 0xC02"
        : "=r"(value)
        :
        : "memory"
    );

    return value;
}


/* ============================================================
 * CYCLEH READ
 *
 * CSR address = 0xC80
 * ============================================================ */

static inline uint32_t read_cycleh(void)
{
    uint32_t value;

    asm volatile (
        "csrr %0, 0xC80"
        : "=r"(value)
        :
        : "memory"
    );

    return value;
}


/* ============================================================
 * MAIN
 * ============================================================ */

int main(void)
{
    volatile uint32_t value = 0;


    /*
     * ========================================================
     * INSTRET
     *
     * CSR = 0xC02
     * ========================================================
     */

    value = read_instret();


    /*
     * ========================================================
     * CYCLEH
     *
     * CSR = 0xC80
     * ========================================================
     */

    value = read_cycleh();


    /*
     * ========================================================
     * PREVENT OPTIMIZATION
     * ========================================================
     */

    (void)value;


    /*
     * ========================================================
     * PASS
     * ========================================================
     */

    test_pass();

    while (1)
    {
        asm volatile ("nop");
    }

    return 0;
}